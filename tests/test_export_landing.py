@real_build
def test_a_provisional_node_keeps_a_keyword_label(payload: dict[str, object]) -> None:
    named, declined, colliding, _methods = el.read_names_tsv(LITE)

    def walk(node: dict[str, object]) -> list[dict[str, object]]:
        out = [node]
        for child in node.get("children", []):  # type: ignore[union-attr]
            out += walk(child)  # type: ignore[arg-type]
        return out

    root = payload["data"]
    assert isinstance(root, dict)
    seen = {n["id"]: n for n in walk(root) if n["id"] != "root"}
    assert seen, "the tree should carry nodes"
    for node_id, node in seen.items():
        if node_id in named:
            assert node["provisional"] is False
            assert node["label"] == named[node_id]
        else:
            assert node["provisional"] is True, f"{node_id} has no usable name"
            assert el.LABEL_SEPARATOR in str(node["label"]) or str(node["label"]) == "unlabelled"
        assert node["declined"] is (node_id in declined)
        if node_id in colliding:
            assert node["provisional"] is True and node["declined"] is False


