def write_tsv(path: Path, fields: list[str], rows: list[dict[str, str]]) -> None:
    """Write a TSV the exporter can read."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, delimiter="\t", lineterminator="\n", fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


NAME_FIELDS = ["theme_id", "name", "method", "unnameable", "duplicate_group"]


@pytest.fixture
def names(tmp_path: Path) -> Path:
    """A names table with one of each kind."""
    path = tmp_path / "names.tsv"
    write_tsv(path, NAME_FIELDS, [
        {"theme_id": "n1", "name": "Interferon alpha signalling", "method": "s1_sample",
         "unnameable": "False", "duplicate_group": ""},
        {"theme_id": "n2", "name": "Neutrophil degranulation", "method": "medoid_no_s1",
         "unnameable": "False", "duplicate_group": ""},
        {"theme_id": "n3", "name": "", "method": "unnameable",
         "unnameable": "True", "duplicate_group": ""},
        {"theme_id": "n4", "name": "Wnt secretion", "method": "medoid_no_s1",
         "unnameable": "False", "duplicate_group": "g07"},
        {"theme_id": "n5", "name": "Wnt secretion", "method": "medoid_no_s1",
         "unnameable": "False", "duplicate_group": "g07"},
    ])
    return path


def test_names_are_split_into_three_kinds(names: Path) -> None:
    named, declined, colliding, methods = el.read_names_tsv(names)
    assert named == {
        "n1": "Interferon alpha signalling",
        "n2": "Neutrophil degranulation",
    }
    assert declined == {"n3"}, "the namer declined this one"
    assert colliding == {"n4", "n5"}, "a name shared by two themes is not usable yet"
    assert methods == {"s1_sample": 1, "medoid_no_s1": 3, "unnameable": 1}


@pytest.mark.parametrize("flag", ["1", "true", "TRUE", "True", "yes"])
def test_unnameable_is_read_tolerantly(tmp_path: Path, flag: str) -> None:
    path = tmp_path / "n.tsv"
    write_tsv(path, NAME_FIELDS, [
        {"theme_id": "n1", "name": "", "method": "unnameable",
         "unnameable": flag, "duplicate_group": ""},
    ])
    _named, declined, _colliding, _methods = el.read_names_tsv(path)
    assert declined == {"n1"}


@pytest.mark.parametrize("flag", ["0", "False", "false", "no", ""])
def test_a_nameable_theme_is_not_declined(tmp_path: Path, flag: str) -> None:
    path = tmp_path / "n.tsv"
    write_tsv(path, NAME_FIELDS, [
        {"theme_id": "n1", "name": "Something", "method": "medoid_no_s1",
         "unnameable": flag, "duplicate_group": ""},
    ])
    named, declined, _colliding, _methods = el.read_names_tsv(path)
    assert named == {"n1": "Something"} and not declined


def test_a_collision_beats_a_name_even_though_the_name_exists(names: Path) -> None:
    # n4 and n5 both have a usable-looking name. Neither is shown, because the page cannot tell
    # them apart and showing one twice would be worse than showing neither.
    named, _declined, colliding, _methods = el.read_names_tsv(names)
    assert "n4" not in named and "n4" in colliding


