"""The landing export's new inputs: a build read from anywhere, and real names.

Two things these tests hold the exporter to. First, a theme is shown with a real name **only** when
the namer accepted it and it is unique -- declined, colliding and out-of-scope themes keep the
keyword label and the amber chip, and those three reasons stay distinguishable. Second, passing no
names file changes nothing: the manifest gains no keys and the old ``theme_names.tsv`` path still
works, because the live page is generated by the default invocation.

Not tested here: the exporter's determinism. It has none -- ``sorted`` over a ``set`` with
case-tied pathway names makes two runs of the same code differ -- which is a pre-existing defect
recorded in ``docs/status/2026-10-15-landing-O50.md``, not something these tests assert either way.
"""

from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path

import pytest

import export_landing as el


def write_tsv(path: Path, fields: list[str], rows: list[dict[str, str]]) -> None:
    """Write a TSV the exporter can read."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, delimiter="\t", lineterminator="\n", fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


NAME_FIELDS = ["theme_id", "name", "method", "unnameable", "duplicate_group"]


@pytest.fixture
def names(tmp_path: Path) -> Path:
    """A names table with one of each kind."""
    path = tmp_path / "names.tsv"
    write_tsv(path, NAME_FIELDS, [
        {"theme_id": "n1", "name": "Interferon alpha signalling", "method": "s1_sample",
         "unnameable": "False", "duplicate_group": ""},
        {"theme_id": "n2", "name": "Neutrophil degranulation", "method": "medoid_no_s1",
         "unnameable": "False", "duplicate_group": ""},
        {"theme_id": "n3", "name": "", "method": "unnameable",
         "unnameable": "True", "duplicate_group": ""},
        {"theme_id": "n4", "name": "Wnt secretion", "method": "medoid_no_s1",
         "unnameable": "False", "duplicate_group": "g07"},
        {"theme_id": "n5", "name": "Wnt secretion", "method": "medoid_no_s1",
         "unnameable": "False", "duplicate_group": "g07"},
    ])
    return path


def test_names_are_split_into_three_kinds(names: Path) -> None:
    named, declined, colliding, methods = el.read_names_tsv(names)
    assert named == {
        "n1": "Interferon alpha signalling",
        "n2": "Neutrophil degranulation",
    }
    assert declined == {"n3"}, "the namer declined this one"
    assert colliding == {"n4", "n5"}, "a name shared by two themes is not usable yet"
    assert methods == {"s1_sample": 1, "medoid_no_s1": 3, "unnameable": 1}


@pytest.mark.parametrize("flag", ["1", "true", "TRUE", "True", "yes"])
def test_unnameable_is_read_tolerantly(tmp_path: Path, flag: str) -> None:
    path = tmp_path / "n.tsv"
    write_tsv(path, NAME_FIELDS, [
        {"theme_id": "n1", "name": "", "method": "unnameable",
         "unnameable": flag, "duplicate_group": ""},
    ])
    _named, declined, _colliding, _methods = el.read_names_tsv(path)
    assert declined == {"n1"}


@pytest.mark.parametrize("flag", ["0", "False", "false", "no", ""])
def test_a_nameable_theme_is_not_declined(tmp_path: Path, flag: str) -> None:
    path = tmp_path / "n.tsv"
    write_tsv(path, NAME_FIELDS, [
        {"theme_id": "n1", "name": "Something", "method": "medoid_no_s1",
         "unnameable": flag, "duplicate_group": ""},
    ])
    named, declined, _colliding, _methods = el.read_names_tsv(path)
    assert named == {"n1": "Something"} and not declined


def test_a_collision_beats_a_name_even_though_the_name_exists(names: Path) -> None:
    # n4 and n5 both have a usable-looking name. Neither is shown, because the page cannot tell
    # them apart and showing one twice would be worse than showing neither.
    named, _declined, colliding, _methods = el.read_names_tsv(names)
    assert "n4" not in named and "n4" in colliding


# ------------------------------------------------------------------ against the real frozen build


FROZEN = Path("data/ontology/frozen/working-O50-2026-10-14")
# The deduplicated names are what the preview ships: the uniqueness pass left 0 collisions.
LITE = Path(
    "data/experiments/naming_O50_2026-10-14/dedup/final_names_O50_lite_unique.tsv"
)
DATA = Path("data")

real_build = pytest.mark.skipif(
    not (FROZEN / "manifest.json").exists() or not LITE.exists()
    or not (DATA / el.PATHWAYS).exists(),
    reason="the frozen O50 build or the lite names are not in this checkout",
)


@pytest.fixture(scope="module")
def payload() -> dict[str, object]:
    return el.build(DATA, "0.4-leaves", "thema_L_x2_O50", build_dir=FROZEN, names_file=LITE)


@real_build
def test_the_manifest_records_the_names_file_and_its_digest(payload: dict[str, object]) -> None:
    meta = payload["manifest"]
    assert isinstance(meta, dict)
    assert meta["names_file"] == str(LITE).replace("\\", "/")
    assert meta["names_sha256"] == hashlib.sha256(LITE.read_bytes()).hexdigest()
    assert meta["named"] is True


@real_build
def test_every_theme_is_named_or_provisional_for_a_stated_reason(
    payload: dict[str, object]
) -> None:
    meta = payload["manifest"]
    assert isinstance(meta, dict)
    total = meta["n_themes"]
    accounted = (
        meta["n_named"] + meta["n_declined"] + meta["n_colliding"]
        + meta["n_out_of_naming_scope"]
    )
    assert accounted == total, "every theme must fall in exactly one of the four buckets"
    assert meta["n_declined"] == 15
    assert meta["n_colliding"] == 0, "the uniqueness pass resolved every collision"
    assert meta["n_out_of_naming_scope"] == 11, "the themes over 200 members"
    assert meta["n_named"] == 4576


@real_build
def test_no_two_themes_share_a_name(payload: dict[str, object]) -> None:
    # What the uniqueness pass was for. Checked on the shipped file, not on the pass's own report.
    named, _declined, colliding, _methods = el.read_names_tsv(LITE)
    assert not colliding
    assert len(set(named.values())) == len(named), "two themes still carry the same name"


@real_build
def test_a_provisional_node_keeps_a_keyword_label(payload: dict[str, object]) -> None:
    named, declined, colliding, _methods = el.read_names_tsv(LITE)

    def walk(node: dict[str, object]) -> list[dict[str, object]]:
        out = [node]
        for child in node.get("children", []):  # type: ignore[union-attr]
            out += walk(child)  # type: ignore[arg-type]
        return out

    root = payload["data"]
    assert isinstance(root, dict)
    seen = {n["id"]: n for n in walk(root) if n["id"] != "root"}
    assert seen, "the tree should carry nodes"
    for node_id, node in seen.items():
        if node_id in named:
            assert node["provisional"] is False
            assert node["label"] == named[node_id]
        else:
            assert node["provisional"] is True, f"{node_id} has no usable name"
            assert el.LABEL_SEPARATOR in str(node["label"]) or str(node["label"]) == "unlabelled"
        assert node["declined"] is (node_id in declined)
        if node_id in colliding:
            assert node["provisional"] is True and node["declined"] is False


@real_build
def test_without_a_names_file_the_manifest_gains_no_keys() -> None:
    # The live page is produced by the default invocation; its shape must not move.
    plain = el.build(DATA, "0.4-leaves", "thema_L_x2_O50", build_dir=FROZEN)
    meta = plain["manifest"]
    assert isinstance(meta, dict)
    for key in ("names_file", "names_sha256", "naming_methods", "n_colliding",
                "n_out_of_naming_scope", "n_themes"):
        assert key not in meta, f"{key} leaked into the default manifest"


@real_build
def test_the_card_assertions_still_hold_on_the_real_collection() -> None:
    # They are gene-level facts from pathways.tsv, so a different build must not move them. If this
    # fails the page is stating a figure that is no longer true.
    pathways = {
        f"{r['source']}:{r['source_id']}": r for r in el.read_rows(DATA / el.PATHWAYS)
    }
    genes = {
        key: frozenset(row["genes"].split(";")) if row["genes"] not in ("", "-") else frozenset()
        for key, row in pathways.items()
    }
    by_name: dict[tuple[str, str], str] = {}
    for key, row in pathways.items():
        by_name.setdefault((row["source"], row["name"].lower()), key)
    universe = len(set().union(*genes.values()))
    el.check_cards(by_name, genes, universe)


@real_build
def test_the_insulin_card_has_no_home_in_this_universe(payload: dict[str, object]) -> None:
    # Recorded as a test because it is a finding, not a defect: universe L drops every curated
    # summary, and all three insulin pathways are summaries, so they are absent from O50 entirely.
    cards = payload["cards"]
    assert isinstance(cards, dict)
    assert cards["insulin"]["node"] is None
    assert cards["nfkb"]["node"] is None, "all four are present but no one theme holds them all"


@real_build
def test_the_build_flag_reads_a_directory_outside_the_versioned_layout(
    payload: dict[str, object]
) -> None:
    meta = payload["manifest"]
    assert isinstance(meta, dict)
    manifest = json.loads((FROZEN / "manifest.json").read_text())
    assert meta["method"] == manifest["method"]
    assert meta["version"] == manifest["version"]
